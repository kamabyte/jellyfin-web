    /*
    |--------------------------------------------------------------------------
    | Как клиент представляется серверу
    |--------------------------------------------------------------------------
    |
    | Видно в панели Jellyfin → Устройства и Активность.
    |
    */

    'client' => env('JELLYFIN_CLIENT', env('APP_NAME', 'Кинотека')),

    'version' => env('JELLYFIN_CLIENT_VERSION', '1.0.0'),

    /*
    |--------------------------------------------------------------------------
    | Воспроизведение
    |--------------------------------------------------------------------------
    |
    | Домашний сервер часто не в силах перекодировать 4K HEVC, поэтому
    | битрейт не ограничиваем: пусть файл идёт как есть или с перепаковкой
    | контейнера, а не пережимается.
    |
    */

    'max_bitrate' => (int) env('JELLYFIN_MAX_BITRATE', 200_000_000),

    'timeout' => (int) env('JELLYFIN_TIMEOUT', 15),

